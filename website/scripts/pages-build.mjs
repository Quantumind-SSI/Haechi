// Assembles the Cloudflare Pages output directory (public/) from the source
// static files.
//
// Cloudflare serves static assets only. The pilot API and its data live in
// Azure Container Apps, so this build emits:
//   config.js  the API base URL the browser posts the form to
//   _headers   security headers whose connect-src permits that API origin
//
// Set HAECHI_API_BASE at build time, for example:
//   HAECHI_API_BASE=https://api.haechi.example npm run pages:build
//
// Leaving it unset produces a same-origin build, which is what the local Node
// server serves.

import { copyFile, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { securityHeaders } from "./security-headers.mjs";

const siteRoot = join(fileURLToPath(import.meta.url), "..", "..");
const outDir = join(siteRoot, "public");

const staticFiles = [
  "index.html",
  "privacy.html",
  "terms.html",
  "styles.css",
  "app.js",
];
const assetDirs = ["assets"];

function normaliseApiBase(value) {
  if (typeof value !== "string" || value.trim() === "") return "";
  const trimmed = value.trim().replace(/\/+$/, "");
  let parsed;
  try {
    parsed = new URL(trimmed);
  } catch {
    throw new Error(`HAECHI_API_BASE is not a valid URL: ${value}`);
  }
  if (parsed.protocol !== "https:") {
    throw new Error("HAECHI_API_BASE must use https");
  }
  return trimmed;
}

async function copyDir(src, dest) {
  await mkdir(dest, { recursive: true });
  for (const entry of await readdir(src, { withFileTypes: true })) {
    const from = join(src, entry.name);
    const to = join(dest, entry.name);
    if (entry.isDirectory()) await copyDir(from, to);
    else await copyFile(from, to);
  }
}

function renderHeadersFile(apiOrigin) {
  const lines = [
    "# Generated by scripts/pages-build.mjs. Do not edit by hand.",
    "/*",
  ];
  for (const [name, value] of Object.entries(securityHeaders({ apiOrigin }))) {
    lines.push(`  ${name}: ${value}`);
  }
  lines.push("");
  return lines.join("\n");
}

function renderConfigFile(apiBase) {
  return [
    "// Generated by scripts/pages-build.mjs. Do not edit by hand.",
    `window.HAECHI_CONFIG = { apiBase: ${JSON.stringify(apiBase)} };`,
    "",
  ].join("\n");
}

async function build() {
  const apiBase = normaliseApiBase(process.env.HAECHI_API_BASE);
  const apiOrigin = apiBase ? new URL(apiBase).origin : "";

  console.log("Building Haechi Pages output...");
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });

  for (const file of staticFiles) {
    await copyFile(join(siteRoot, file), join(outDir, file));
    console.log(`  copied ${file}`);
  }
  for (const dir of assetDirs) {
    await copyDir(join(siteRoot, dir), join(outDir, dir));
    console.log(`  copied ${dir}/`);
  }

  await writeFile(join(outDir, "config.js"), renderConfigFile(apiBase), "utf8");
  console.log(`  wrote config.js (apiBase: ${apiBase || "same-origin"})`);

  await writeFile(
    join(outDir, "_headers"),
    renderHeadersFile(apiOrigin),
    "utf8",
  );
  console.log("  wrote _headers");

  console.log(`\nPages build complete: ${outDir}`);
}

build().catch((error) => {
  console.error("Pages build failed:", error.message);
  process.exit(1);
});
