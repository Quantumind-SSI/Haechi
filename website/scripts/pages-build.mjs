// Assembles a clean Cloudflare Pages output directory (public/) from the source
// static files, and generates the _headers file from the shared SECURITY_HEADERS
// so the static site keeps the same security posture as the Node origin.
//
// Functions live in ../functions and are compiled by Cloudflare separately; they
// are intentionally NOT copied into the static output.

import { copyFile, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { SECURITY_HEADERS } from "../functions/_lib.js";

const siteRoot = join(fileURLToPath(import.meta.url), "..", "..");
const outDir = join(siteRoot, "public");

const staticFiles = [
  "index.html",
  "privacy.html",
  "terms.html",
  "styles.css",
  "app.js",
];
const assetDirs = ["assets"];

async function copyDir(src, dest) {
  await mkdir(dest, { recursive: true });
  for (const entry of await readdir(src, { withFileTypes: true })) {
    const from = join(src, entry.name);
    const to = join(dest, entry.name);
    if (entry.isDirectory()) await copyDir(from, to);
    else await copyFile(from, to);
  }
}

function renderHeadersFile() {
  const lines = [
    "# Generated by scripts/pages-build.mjs. Do not edit by hand.",
    "/*",
  ];
  for (const [name, value] of Object.entries(SECURITY_HEADERS)) {
    lines.push(`  ${name}: ${value}`);
  }
  lines.push("");
  return lines.join("\n");
}

async function build() {
  console.log("Building Haechi Pages output...");
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });

  for (const file of staticFiles) {
    await copyFile(join(siteRoot, file), join(outDir, file));
    console.log(`  copied ${file}`);
  }
  for (const dir of assetDirs) {
    await copyDir(join(siteRoot, dir), join(outDir, dir));
    console.log(`  copied ${dir}/`);
  }

  await writeFile(join(outDir, "_headers"), renderHeadersFile(), "utf8");
  console.log("  wrote _headers");

  console.log(`\nPages build complete: ${outDir}`);
}

build().catch((error) => {
  console.error("Pages build failed:", error);
  process.exit(1);
});
